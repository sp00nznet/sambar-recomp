#!/usr/bin/env python3
"""Sambar Server lift driver: work/<module>.functions.json -> src/recomp/gen/<module>/.

Sambar is a small front end (ntserver.exe) on an engine DLL and its helper
DLLs, every one of them lifted. Each module is lifted by pcrecomp's shared
driver (tools/lift/drive32.py) into its own directory; the declarations and
the dispatch table cover every module and are rebuilt from
work/<module>.entries.json on every run. The modules were rebased first
(tools/catalog.py, with pcrecomp tools/pe/rebase.py), so every sub_XXXXXXXX
is unique across them.

    py -3 run_lift.py                       # every module in work/bases.json
    py -3 run_lift.py sambar.dll            # just this one
"""
import argparse
import json
import os
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
_TOOLS = os.path.join(os.environ.get('PCRECOMP', os.path.join(_HERE, '..', 'pcrecomp')), 'tools')
sys.path.insert(0, os.path.join(_TOOLS, 'lift'))
sys.path.insert(0, os.path.join(_TOOLS, 'pe'))

import pefile                                              # noqa: E402
from drive32 import lift_image                             # noqa: E402

WORK = os.path.join(_HERE, 'work')
OUT = os.path.join(_HERE, 'src', 'recomp', 'gen')
# Sambar 6.4 production, 2006-07-08 (PE stamps): another build is refused.
STAMPS = {'ntserver.exe': 0x449C5840, 'sambar.dll': 0x449C622C}


def put(path, text):
    """Write only a change: every chunk includes recomp_funcs.h, so rewriting
    it unchanged would rebuild every chunk after lifting one module."""
    if not os.path.exists(path) or open(path, newline='').read() != text:
        with open(path, 'w', newline='\n') as f:
            f.write(text)


def write_tables(modules):
    entries = []
    for name in modules:
        p = os.path.join(WORK, name + '.entries.json')
        if os.path.exists(p):
            entries += json.load(open(p))
    entries.sort()
    put(os.path.join(OUT, 'recomp_funcs.h'),
        '/* AUTO-GENERATED by run_lift.py */\n#pragma once\n#include <stdint.h>\n\n'
        + ''.join('void sub_%08X(void);\n' % a for a in entries))
    put(os.path.join(OUT, 'recomp_dispatch.c'),
        '/* AUTO-GENERATED by run_lift.py */\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n\n'
        'const recomp_dispatch_entry_t recomp_dispatch_table[] = {\n'
        + ''.join('    { 0x%08Xu, sub_%08X },\n' % (a, a) for a in entries)
        + '};\nconst uint32_t recomp_dispatch_count = %d;\n' % len(entries))
    return len(entries)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('modules', nargs='*', help='modules to lift (default: all in work/bases.json)')
    ap.add_argument('--split', type=int, default=400, help='functions per .c file')
    args = ap.parse_args()
    bases = os.path.join(WORK, 'bases.json')
    if not os.path.exists(bases):
        sys.exit('no %s -- run tools/catalog.py first (README, Step by step)' % bases)
    modules = list(json.load(open(bases)))
    t0 = time.time()
    stats_path = os.path.join(WORK, 'lift_stats.json')
    stats = json.load(open(stats_path)) if os.path.exists(stats_path) else {}
    os.makedirs(OUT, exist_ok=True)
    for name in args.modules or modules:
        orig = os.path.join(_HERE, 'game', 'bin', name)
        if name in STAMPS and pefile.PE(orig, fast_load=True).FILE_HEADER.TimeDateStamp != STAMPS[name]:
            sys.exit('%s is not Sambar 6.4p (PE stamp 0x%08X expected); the README says where to get it'
                     % (orig, STAMPS[name]))
        seeds = os.path.join(_HERE, 'seeds', name + '.json')     # addresses found in bring-up
        st, entries = lift_image(os.path.join(WORK, 'rebased', name), os.path.join(WORK, name + '.functions.json'),
                                 os.path.join(OUT, os.path.splitext(name)[0]), split=args.split,
                                 seeds=json.load(open(seeds)) if os.path.exists(seeds) else ())
        json.dump(entries, open(os.path.join(WORK, name + '.entries.json'), 'w'))
        stats[name] = st
    json.dump(stats, open(stats_path, 'w'), indent=1)
    n = write_tables(modules)
    print('=' * 60)
    print('  %d entries in the dispatch table, lift errors %d, unimplemented instructions %d, %.0fs'
          % (n, sum(s['errors'] for s in stats.values()),
             sum(sum(s.get('unimplemented', {}).values()) for s in stats.values()), time.time() - t0))
    print('=' * 60)


if __name__ == '__main__':
    main()
